    private void btnAddMovieActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddMovieActionPerformed
        // TODO add your handling code here:
        String movieName = txtMovieName.getText();
        String genre = txtGenre.getText();
        String duration = txtDuration.getText();
        String language = txtLanguage.getText();
        String releaseDate = txtReleaseDate.getText(); 

        if(movieName.isEmpty() || genre.isEmpty() ||
        duration.isEmpty() || language.isEmpty() ||
        releaseDate.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                "Please fill all fields!");
            return;
        }
        try {

        Connection con = DBConnection.getConnection();

        String sql =
        "INSERT INTO movies(movie_name,genre,duration,language,release_date) VALUES(?,?,?,?,?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, movieName);
        pst.setString(2, genre);
        pst.setString(3, duration);
        pst.setString(4, language);
        pst.setDate(5, java.sql.Date.valueOf(releaseDate));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Movie Added Successfully!");

        txtMovieName.setText("");
        txtGenre.setText("");
        txtDuration.setText("");
        txtLanguage.setText("");
        txtReleaseDate.setText("");

    } catch(Exception e) {

        JOptionPane.showMessageDialog(this, e);

    }
    }//GEN-LAST:event_btnAddMovieActionPerformed

