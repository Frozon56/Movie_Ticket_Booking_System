    public void setTicketData(String movie,
                          String seats,
                          String amount,
                          String showtime,
                          String ticketCount) {

   name.setText(UserSession.loggedInUser);
    movieName.setText(movie);
    seatNo.setText(seats);
    totalAmount.setText(amount);
    showTime.setText(showtime);
    noTicket.setText(ticketCount);

    tid.setText("T" + System.currentTimeMillis());

    java.text.SimpleDateFormat sdf =
            new java.text.SimpleDateFormat("dd-MM-yyyy HH:mm");

    bookingDate.setText(
            sdf.format(new java.util.Date())
    );
}

