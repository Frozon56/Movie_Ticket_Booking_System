    private void btnPayNowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayNowActionPerformed
String movie = txtMovie.getText();
    String seats = txtSeats.getText();
    String ticketCount = String.valueOf(seats.split(",").length);
    String amount = txtAmount.getText();
    if(seats.equals("")|| amount.equals("")){
    JOptionPane.showMessageDialog(this, "Seats or Amount field is empty!");
            }
    else{
        try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO payments(movie_name,seats,amount,payment_method,card_number,upi_id) VALUES(?,?,?,?,?,?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtMovie.getText());
        pst.setString(2, txtSeats.getText());
        pst.setDouble(3, Double.parseDouble(txtAmount.getText()));
        pst.setString(4, "Card"); // or UPI
        pst.setString(5, txtCardNumber.getText());
        pst.setString(6, txtUPI.getText());

        pst.executeUpdate();
        String sql2 ="INSERT INTO bookings(movie_name,theatre,show_time,seats,amount) VALUES(?,?,?,?,?)";

        PreparedStatement pst2 = con.prepareStatement(sql2);

        pst2.setString(1, txtMovie.getText());
        pst2.setString(2, theatre);
        pst2.setString(3, showTime);
        pst2.setString(4, txtSeats.getText());
        pst2.setDouble(5, Double.parseDouble(txtAmount.getText()));

        pst2.executeUpdate();

    } catch(Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    javax.swing.JOptionPane.showMessageDialog(this,
        "Movie: " + movie +
        "\nSeats: " + seats +
        "\nAmount: " + amount +
        "\nPayment Successful!");   
        
    Ticket t1=new Ticket();
    t1.setTicketData(
    txtMovie.getText(),
    txtSeats.getText(),
    txtAmount.getText(),
    showTime,
    ticketCount
);
    t1.setVisible(true);
    this.dispose();

    } // TODO add your handling code here:
    }//GEN-LAST:event_btnPayNowActionPerformed

