    private void CreateAccButtobActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CreateAccButtobActionPerformed
    String name = txtName.getText();
        String email = txtEmail.getText();
        String password = String.valueOf(txtPassword.getPassword());
        String phone = txtPhone.getText();

    if(name.isEmpty() || email.isEmpty() ||
       password.isEmpty() || phone.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill all fields!");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();
        
        String sql =
"INSERT INTO users(full_name,email,password,phone) VALUES(?,?,?,?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, name);
        pst.setString(2, email);
        pst.setString(3, password);
        pst.setString(4, phone);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Registration Successful!");

        LoginPg l = new LoginPg();
        l.setVisible(true);
        this.dispose();

    } catch(Exception e) {
        //e.printStackTrace();
        JOptionPane.showMessageDialog(this, e);
    }
// TODO add your handling code here:
    }//GEN-LAST:event_CreateAccButtobActionPerformed

